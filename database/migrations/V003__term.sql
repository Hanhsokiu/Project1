-- V003: THESIS_TERM, TERM_PHASE, TERM_PARAMETER, TERM_LECTURER, PROJECT_GROUP, TERM_STUDENT

CREATE TABLE "THESIS_TERM" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    academic_year VARCHAR(50) NOT NULL,
    semester INT NOT NULL,
    status VARCHAR(50) DEFAULT 'DRAFT',
    start_date TIMESTAMP WITH TIME ZONE NOT NULL,
    end_date TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "TERM_PHASE" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    phase_name VARCHAR(100) NOT NULL,
    start_date TIMESTAMP WITH TIME ZONE NOT NULL,
    end_date TIMESTAMP WITH TIME ZONE NOT NULL,
    is_locked BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "TERM_PARAMETER" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    key VARCHAR(100) NOT NULL,
    value TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_term_param UNIQUE (term_id, key)
);

CREATE TABLE "TERM_LECTURER" (
    term_id VARCHAR(36) REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    lecturer_id VARCHAR(36) REFERENCES "LECTURER"(id) ON DELETE CASCADE,
    quota INT DEFAULT 5,
    PRIMARY KEY (term_id, lecturer_id)
);

CREATE TABLE "TERM_STUDENT" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    student_id VARCHAR(36) NOT NULL REFERENCES "STUDENT"(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_term_student UNIQUE (term_id, student_id)
);
