-- V007: DEFENSE_ELIGIBILITY, DEFERMENT_REQUEST, REVIEWER_ASSIGNMENT, DEFENSE_COMMITTEE, COMMITTEE_MEMBER, ROOM, DEFENSE_SESSION, COMMITTEE_STUDENT, DEFENSE_MINUTES

CREATE TABLE "DEFENSE_ELIGIBILITY" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    status VARCHAR(50) DEFAULT 'PENDING',
    checked_at TIMESTAMP WITH TIME ZONE,
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "DEFERMENT_REQUEST" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    status VARCHAR(50) DEFAULT 'PENDING',
    requested_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "REVIEWER_ASSIGNMENT" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    reviewer_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    assigned_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reviewer_prop UNIQUE (proposal_id, reviewer_id)
);

CREATE TABLE "ROOM" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    capacity INT NOT NULL,
    location VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "DEFENSE_COMMITTEE" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "COMMITTEE_MEMBER" (
    committee_id VARCHAR(36) REFERENCES "DEFENSE_COMMITTEE"(id) ON DELETE CASCADE,
    lecturer_id VARCHAR(36) REFERENCES "LECTURER"(id) ON DELETE CASCADE,
    role VARCHAR(50) NOT NULL,
    PRIMARY KEY (committee_id, lecturer_id)
);

CREATE TABLE "DEFENSE_SESSION" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    committee_id VARCHAR(36) NOT NULL REFERENCES "DEFENSE_COMMITTEE"(id) ON DELETE CASCADE,
    room_id VARCHAR(36) NOT NULL REFERENCES "ROOM"(id),
    scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_min INT DEFAULT 30,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "COMMITTEE_STUDENT" (
    session_id VARCHAR(36) REFERENCES "DEFENSE_SESSION"(id) ON DELETE CASCADE,
    proposal_id VARCHAR(36) REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    order_index INT NOT NULL,
    PRIMARY KEY (session_id, proposal_id)
);

CREATE TABLE "DEFENSE_MINUTES" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    session_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "DEFENSE_SESSION"(id) ON DELETE CASCADE,
    content JSONB,
    file_path TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
