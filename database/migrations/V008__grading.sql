-- V008: RUBRIC_CRITERIA, SCORE_ENTRY, SCORE_DETAIL, FINAL_RESULT

CREATE TABLE "RUBRIC_CRITERIA" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    weight NUMERIC(5, 2) NOT NULL,
    max_score NUMERIC(4, 1) DEFAULT 10.0,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "SCORE_ENTRY" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    scorer_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    role VARCHAR(50) NOT NULL,
    total_score NUMERIC(4, 1),
    is_locked BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_score_entry UNIQUE (proposal_id, scorer_id, role)
);

CREATE TABLE "SCORE_DETAIL" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    score_entry_id VARCHAR(36) NOT NULL REFERENCES "SCORE_ENTRY"(id) ON DELETE CASCADE,
    rubric_criteria_id VARCHAR(36) NOT NULL REFERENCES "RUBRIC_CRITERIA"(id),
    score NUMERIC(4, 1) NOT NULL,
    comment TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_score_detail UNIQUE (score_entry_id, rubric_criteria_id)
);

CREATE TABLE "FINAL_RESULT" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    advisor_score NUMERIC(4, 1),
    reviewer_score NUMERIC(4, 1),
    final_score NUMERIC(4, 1),
    is_passed BOOLEAN,
    is_published BOOLEAN DEFAULT FALSE,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
