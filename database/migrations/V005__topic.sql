-- V005: TOPIC, TOPIC_HISTORY, PROPOSAL, PROPOSAL_VERSION, REVIEW_GROUP, REVIEW_GROUP_MEMBER, PROPOSAL_REVIEW, THESIS_DOSSIER

CREATE TABLE "TOPIC" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    research_area_id VARCHAR(36) REFERENCES "RESEARCH_AREA"(id),
    title VARCHAR(500) NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "TOPIC_HISTORY" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    topic_id VARCHAR(36) NOT NULL REFERENCES "TOPIC"(id) ON DELETE CASCADE,
    changed_by VARCHAR(36) NOT NULL,
    old_value JSONB,
    new_value JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "PROPOSAL" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    topic_id VARCHAR(36) NOT NULL REFERENCES "TOPIC"(id) ON DELETE CASCADE,
    student_id VARCHAR(36) NOT NULL UNIQUE REFERENCES "STUDENT"(id),
    status VARCHAR(50) DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "PROPOSAL_VERSION" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    version INT NOT NULL,
    content JSONB NOT NULL,
    file_path TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_proposal_version UNIQUE (proposal_id, version)
);

CREATE TABLE "REVIEW_GROUP" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "REVIEW_GROUP_MEMBER" (
    review_group_id VARCHAR(36) REFERENCES "REVIEW_GROUP"(id) ON DELETE CASCADE,
    lecturer_id VARCHAR(36) REFERENCES "LECTURER"(id) ON DELETE CASCADE,
    PRIMARY KEY (review_group_id, lecturer_id)
);

CREATE TABLE "PROPOSAL_REVIEW" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    review_group_id VARCHAR(36) NOT NULL REFERENCES "REVIEW_GROUP"(id),
    decision VARCHAR(50),
    comment TEXT,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "THESIS_DOSSIER" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    status VARCHAR(50) DEFAULT 'DRAFT',
    file_path TEXT,
    submitted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
