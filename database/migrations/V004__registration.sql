-- V004: REGISTRATION, REGISTRATION_PREF, ASSIGNMENT_PLAN, ADVISOR_ASSIGNMENT

CREATE TABLE "REGISTRATION" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    student_id VARCHAR(36) NOT NULL REFERENCES "STUDENT"(id),
    status VARCHAR(50) DEFAULT 'PENDING',
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reg_term_student UNIQUE (term_id, student_id)
);

CREATE TABLE "REGISTRATION_PREF" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    registration_id VARCHAR(36) NOT NULL REFERENCES "REGISTRATION"(id) ON DELETE CASCADE,
    lecturer_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    preference_order INT NOT NULL,
    CONSTRAINT uq_reg_pref UNIQUE (registration_id, preference_order)
);

CREATE TABLE "ASSIGNMENT_PLAN" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    term_id VARCHAR(36) NOT NULL REFERENCES "THESIS_TERM"(id) ON DELETE CASCADE,
    status VARCHAR(50) DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE "ADVISOR_ASSIGNMENT" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    assignment_plan_id VARCHAR(36) NOT NULL REFERENCES "ASSIGNMENT_PLAN"(id) ON DELETE CASCADE,
    registration_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "REGISTRATION"(id),
    advisor_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    is_manual BOOLEAN DEFAULT FALSE,
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
