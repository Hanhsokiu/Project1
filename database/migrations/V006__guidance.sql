-- V006: GUIDANCE_PLAN, TASK, TASK_SUBMISSION, SUBMISSION_FILE, TASK_REVIEW, GUIDANCE_MEETING, PHASE_EVALUATION, FINAL_REPORT, DEFENSE_CONFIRMATION

CREATE TABLE "GUIDANCE_PLAN" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    advisor_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "TASK" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    guidance_plan_id VARCHAR(36) NOT NULL REFERENCES "GUIDANCE_PLAN"(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(50) DEFAULT 'TODO',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "TASK_SUBMISSION" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    task_id VARCHAR(36) NOT NULL REFERENCES "TASK"(id) ON DELETE CASCADE,
    content TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "SUBMISSION_FILE" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    submission_id VARCHAR(36) NOT NULL REFERENCES "TASK_SUBMISSION"(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    file_path TEXT NOT NULL,
    file_size INT NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "TASK_REVIEW" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    submission_id VARCHAR(36) NOT NULL REFERENCES "TASK_SUBMISSION"(id) ON DELETE CASCADE,
    reviewer_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    comment TEXT,
    is_passed BOOLEAN NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "GUIDANCE_MEETING" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    guidance_plan_id VARCHAR(36) NOT NULL REFERENCES "GUIDANCE_PLAN"(id) ON DELETE CASCADE,
    meeting_date TIMESTAMP WITH TIME ZONE NOT NULL,
    location VARCHAR(255),
    summary TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "PHASE_EVALUATION" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    guidance_plan_id VARCHAR(36) NOT NULL REFERENCES "GUIDANCE_PLAN"(id) ON DELETE CASCADE,
    phase_name VARCHAR(100) NOT NULL,
    score NUMERIC(4, 1),
    comment TEXT,
    evaluated_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "FINAL_REPORT" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    file_path TEXT,
    submitted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "DEFENSE_CONFIRMATION" (
    id VARCHAR(36) PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    proposal_id VARCHAR(36) UNIQUE NOT NULL REFERENCES "PROPOSAL"(id) ON DELETE CASCADE,
    advisor_id VARCHAR(36) NOT NULL REFERENCES "LECTURER"(id),
    status VARCHAR(50) DEFAULT 'PENDING',
    note TEXT,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
