BEGIN;
SET LOCAL lock_timeout = '10s';
ALTER TABLE "GUIDANCE_PERIOD"
 ADD COLUMN description TEXT NOT NULL DEFAULT '',
 ADD COLUMN "expectedDeliverables" TEXT NOT NULL DEFAULT 'Báo cáo tiến độ và mã nguồn',
 ADD COLUMN state VARCHAR(16),
 ADD COLUMN "publishedAt" TIMESTAMPTZ(6),
 ADD COLUMN "createdByUserId" TEXT REFERENCES "USER_ACCOUNT"(id) ON DELETE RESTRICT,
 ADD COLUMN "updatedByUserId" TEXT REFERENCES "USER_ACCOUNT"(id) ON DELETE RESTRICT,
 ADD COLUMN "stateReason" TEXT,
 ADD COLUMN "allowLate" BOOLEAN NOT NULL DEFAULT true,
 ADD CONSTRAINT weekly_period_state CHECK (state IS NULL OR state IN ('DRAFT','OPEN','LOCKED'));
ALTER TABLE "TASK_WORKFLOW"
 ADD COLUMN "draftReport" JSONB,
 ADD COLUMN "draftRevision" INTEGER NOT NULL DEFAULT 0,
 ADD COLUMN "completionCriteria" TEXT NOT NULL DEFAULT '',
 ADD COLUMN priority INTEGER NOT NULL DEFAULT 2 CHECK(priority BETWEEN 1 AND 3);
ALTER TABLE "SUBMISSION_WORKFLOW" ADD COLUMN "reportContent" JSONB, ADD COLUMN "changeExplanation" TEXT;
ALTER TABLE "PROGRESS_REVIEW" ADD COLUMN "revisionDueAt" TIMESTAMPTZ(6);
CREATE TABLE "GUIDANCE_REOPEN" (
 id VARCHAR(36) PRIMARY KEY,
 "submissionId" TEXT NOT NULL UNIQUE REFERENCES "TASK_SUBMISSION"(id) ON DELETE RESTRICT,
 "actorId" TEXT NOT NULL REFERENCES "USER_ACCOUNT"(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL CHECK(length(trim(reason)) > 0),
 "revisionDueAt" TIMESTAMPTZ(6) NOT NULL,
 "createdAt" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK("revisionDueAt" > "createdAt")
);
CREATE FUNCTION weekly_reopen_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Reopen decisions are append-only' USING ERRCODE='23514'; END $$;
CREATE TRIGGER weekly_reopen_immutable BEFORE UPDATE OR DELETE ON "GUIDANCE_REOPEN"
 FOR EACH ROW EXECUTE FUNCTION weekly_reopen_immutable();
CREATE INDEX "GUIDANCE_PERIOD_termId_state_reportDueAt_idx" ON "GUIDANCE_PERIOD"("termId",state,"reportDueAt");
COMMIT;
