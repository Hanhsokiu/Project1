const fs = require("node:fs");
const path = require("node:path");

// Keep the checked-in contract in sync with the running Nest application.
const endpoint =
  process.env.OPENAPI_URL || "http://127.0.0.1:3010/api/docs-json";
function scalar(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (!Object.keys(value).length) return Array.isArray(value) ? "[]" : "{}";
  return undefined;
}
function yaml(value, depth = 0) {
  const indent = "  ".repeat(depth);
  const oneLine = scalar(value);
  if (oneLine !== undefined) return indent + oneLine;
  if (Array.isArray(value))
    return value
      .map((item) => {
        const itemScalar = scalar(item);
        return itemScalar === undefined
          ? indent + "-\n" + yaml(item, depth + 1)
          : indent + "- " + itemScalar;
      })
      .join("\n");
  return Object.entries(value)
    .map(([key, item]) => {
      const itemScalar = scalar(item);
      return (
        indent +
        JSON.stringify(key) +
        ":" +
        (itemScalar === undefined
          ? "\n" + yaml(item, depth + 1)
          : " " + itemScalar)
      );
    })
    .join("\n");
}
async function main() {
  const response = await fetch(endpoint);
  if (!response.ok) throw new Error(`OpenAPI HTTP ${response.status}`);
  const document = await response.json();
  if (
    !document.openapi ||
    !document.paths ||
    !document.components?.schemas?.TermInput
  )
    throw new Error(
      "The running API does not contain the Step 1 contract; rebuild/restart it first.",
    );
  let references = 0;
  function validateReferences(value) {
    if (!value || typeof value !== "object") return;
    if (
      typeof value.$ref === "string" &&
      value.$ref.startsWith("#/components/schemas/")
    ) {
      references++;
      if (!document.components.schemas[value.$ref.split("/").pop()])
        throw new Error(`OpenAPI reference not found: ${value.$ref}`);
    }
    Object.values(value).forEach(validateReferences);
  }
  validateReferences(document);
  const dir = path.resolve(__dirname, "../../docs/api");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "openapi.json"),
    JSON.stringify(document, null, 2) + "\n",
  );
  fs.writeFileSync(
    path.join(dir, "openapi.yaml"),
    "# Generated by npm run docs:api against the running Nest application.\n" +
      yaml(document) +
      "\n",
  );
  console.log(
    `Exported ${Object.keys(document.paths).length} paths, ${Object.keys(document.components.schemas).length} schemas; verified ${references} schema references. Files: docs/api/openapi.{json,yaml}`,
  );
}
main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
